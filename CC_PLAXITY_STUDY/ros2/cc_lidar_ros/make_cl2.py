"""Generates src/lidar_ros_cl2.cpp from the frozen src/lidar_ros_cl.cpp by exact, counted text replacements (Addendum O)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
s = open(os.path.join(here, "src/lidar_ros_cl.cpp")).read()
BS = chr(92)


def rep(a, b, n=1):
    global s
    assert s.count(a) == n, (a[:60], s.count(a))
    s = s.replace(a, b)


rep("// lidar_ros_cl.cpp -- G12 (Addendum F):", """// lidar_ros_cl2.cpp -- Addendum O (closed loop v2). GENERATED by make_cl2.py from lidar_ros_cl.cpp (kept frozen). Changes:
//  * policy kp     : UNCHANGED legacy monitor (state updated on undegraded frames only, plain ACI) -- the G12 method.
//  * policy kpm    : MODE-AWARE state update: a frame degraded at release also updates the cross-frame state, normalised by the
//                    degraded-mode median ME2E_D (z = log(e2e / ME2E_D)); frames degraded later (at N2) are skipped.
//                    Plus the burst guard (W = 50, kappa = 0.05) on the threshold.
//  * policy kpmwh  : kpm + weakly-hard rule (m = 4, K = 20), general-lag form: before release, c = known unwarned misses +
//                    still-running unwarned frames among the last K-1 releases; if c >= m the frame is warned (forced).
//  * policy none   : logs what kpm would do (no action). toba / random as before (their logged KP state is mode-aware).
//  * extra parameter line: ME2E_D. Extra CSV column: forced.
// lidar_ros_cl.cpp -- G12 (Addendum F):""")
rep("static double LAM, Q, Q0, ME2E, DL, THETA0, ALPHA, GAMMA, MED[NN], BB[NN], VV[NN], THR[7];",
    "static double LAM, Q, Q0, ME2E, DL, THETA0, ALPHA, GAMMA, MED[NN], BB[NN], VV[NN], THR[7], ME2E_D = 0;\n"
    "static constexpr int W_BG = 50, WH_M = 4, WH_K = 20; static constexpr double KAPPA = 0.05;")
rep("  for (int v = 1; v <= 6; v++) { int n; f >> n; CDF[v].resize(n); for (int i = 0; i < n; i++) f >> CDF[v][i]; }\n  return (bool)f;",
    "  for (int v = 1; v <= 6; v++) { int n; f >> n; CDF[v].resize(n); for (int i = 0; i < n; i++) f >> CDF[v][i]; }\n  f >> ME2E_D;\n  return (bool)f && ME2E_D > 0;")
rep("  int alarm = -1, degr = 0, npts = 0; std::atomic<int> cp2{0};",
    "  int alarm = -1, degr = 0, npts = 0, errk = -1, forced = 0; std::atomic<int> cp2{0};   // errk: -1 outcome unknown, else 0/1")
rep("static void kp_check(Rec &r, int k, double elapsed)", """// Effective threshold and weakly-hard budget at the release of frame f (call with MU held). Scans the last releases.
static double guard_at(int f) {
  int s = 0; for (int j = f - 1; j >= 0 && j >= f - W_BG; j--) if (REC[j].errk == 1) s++;
  double g = KAPPA * (s - ALPHA * W_BG); return g > 0 ? g : 0.0;
}
static bool budget_spent(int f) {
  int c = 0; for (int j = f - 1; j >= 0 && j >= f - (WH_K - 1); j--) { const Rec &q = REC[j]; if (q.errk == 1 || (q.errk < 0 && q.alarm < 0)) c++; }
  return c >= WH_M;
}
static void kp_check(Rec &r, int k, double elapsed)""")
rep("""      r.theta = THETA;
      bool hit = POLICY == "kp" ? r.p[0] > THETA : POLICY == "toba" ? r.tb[0] < THR[1] :
                 POLICY == "random" ? std::uniform_real_distribution<double>(0, 1)(RNG) < PRAND : false;
      if (POLICY == "kp" && r.p[0] > THETA) r.alarm = 0;          // logged alarm (actionable) for the kp policy
      if (POLICY != "kp" && POLICY != "none" && hit) r.alarm = 0;
      if (POLICY == "none" && r.p[0] > THETA) r.alarm = 0;        // what KP+ACI WOULD do (no action)
      if (hit && POLICY != "none") r.degr = 1;""",
    """      bool legacy = POLICY == "kp", ours = POLICY == "kpm" || POLICY == "kpmwh" || POLICY == "none";
      r.theta = ours ? THETA - guard_at(f) : THETA;                 // effective threshold of this frame (used again at cp1)
      if (POLICY == "kpmwh" && budget_spent(f)) r.forced = 1;
      bool hit = (legacy || ours) ? (r.p[0] > r.theta || r.forced) : POLICY == "toba" ? r.tb[0] < THR[1] :
                 POLICY == "random" ? std::uniform_real_distribution<double>(0, 1)(RNG) < PRAND : false;
      if (hit) r.alarm = 0;                                         // for 'none': what kpm WOULD do (no action)
      if (hit && POLICY != "none") r.degr = 1;""")
rep("""        if ((POLICY == "kp" || POLICY == "none") && kh) r.alarm = 1;
        if (POLICY == "toba" && th) r.alarm = 1;
        if (r.alarm == 1 && (POLICY == "kp" || POLICY == "toba") && !r.degr) { r.degr = 2; halve(pts); }""",
    """        if ((POLICY == "kp" || POLICY == "kpm" || POLICY == "kpmwh" || POLICY == "none") && kh) r.alarm = 1;
        if (POLICY == "toba" && th) r.alarm = 1;
        if (r.alarm == 1 && POLICY != "none" && !r.degr) { r.degr = 2; halve(pts); }""")
rep("""      if (!r.degr) { double z = std::log(r.e[5] / ME2E); CUR = HAVE ? LAM * CUR + (1 - LAM) * z : z; HAVE = 1; }
      double err = (r.e[5] > DL && r.alarm < 0) ? 1.0 : 0.0;   // unwarned actionable miss (alarm < 0: none at cp0/cp1)
      THETA -= GAMMA * (err - ALPHA);""",
    """      bool legacy = POLICY == "kp";
      if (!r.degr || (!legacy && r.degr == 1)) {                 // mode-aware: release-degraded frames are normalised by ME2E_D
        double z = std::log(r.e[5] / (r.degr ? ME2E_D : ME2E)); CUR = HAVE ? LAM * CUR + (1 - LAM) * z : z; HAVE = 1; }
      double err = (r.e[5] > DL && r.alarm < 0) ? 1.0 : 0.0;   // unwarned actionable miss (alarm < 0: none at cp0/cp1)
      r.errk = (int)err;
      THETA -= GAMMA * (err - ALPHA);""")
rep('"p0,p1,p2,p3,theta,tb1,tb2,us_kp,us_tb' + BS + 'n");', '"p0,p1,p2,p3,theta,tb1,tb2,us_kp,us_tb,forced' + BS + 'n");')
rep('%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.2f,%.2f' + BS + 'n",', '%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.2f,%.2f,%d' + BS + 'n",')
rep("r.theta, r.tb[0], r.tb[1], r.us_kp, r.us_tb); }", "r.theta, r.tb[0], r.tb[1], r.us_kp, r.us_tb, r.forced); }")
rep("usage: lidar_ros_cl <scan_dir>", "usage: lidar_ros_cl2 <scan_dir>")
open(os.path.join(here, "src/lidar_ros_cl2.cpp"), "w", newline="\n").write(s)
c = open(os.path.join(here, "CMakeLists.txt")).read()
if "lidar_ros_cl2" not in c:
    c = c.replace("add_executable(lidar_ros_tm src/lidar_ros_tm.cpp)",
                  "add_executable(lidar_ros_cl2 src/lidar_ros_cl2.cpp)\ntarget_compile_options(lidar_ros_cl2 PRIVATE -O2)\n"
                  "ament_target_dependencies(lidar_ros_cl2 rclcpp sensor_msgs std_msgs)\nadd_executable(lidar_ros_tm src/lidar_ros_tm.cpp)")
    c = c.replace("install(TARGETS lidar_ros lidar_ros_cl lidar_ros_tm", "install(TARGETS lidar_ros lidar_ros_cl lidar_ros_cl2 lidar_ros_tm")
    open(os.path.join(here, "CMakeLists.txt"), "w", newline="\n").write(c)
print("ok")
